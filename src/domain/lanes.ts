/**
 * 두 레인 (SSOT §5). 7영역을 성격이 다른 두 갈래로 다룬다.
 *
 *   학습(활동) 레인 = 국어·영어·수학·과학·탐구·예체능 — 학원·활동·추천·pull 이 붙는다.
 *   생활·마음(안심) 레인 = 사회·인성·건강·안전 — 저액션·안심. 빈칸을 갭 알람으로 띄우지 않는다.
 *
 * 왜 갈리나: 국영수예는 부모가 학교를 못 믿어 사교육하므로 "네가 시키는 게 이만큼 챙김"으로 안심.
 * 사회·인성·건강은 부모가 유치원 담당을 인정하고 사교육도 안 하므로 "유치원·일상에서 챙겨짐"이 정직.
 * (예체능은 미술·피아노·태권도처럼 사교육이 활발 → 학습 레인. 전략 결정 2026-09.)
 */
import type { Domain } from './types'

export type Lane = '학습' | '생활·마음'

/** 생활·마음(안심) 레인 영역. 나머지는 모두 학습(활동) 레인. */
export const LIFE_DOMAINS: readonly Domain[] = ['사회·인성', '건강·안전']

export function laneOf(domain: Domain): Lane {
  return LIFE_DOMAINS.includes(domain) ? '생활·마음' : '학습'
}
